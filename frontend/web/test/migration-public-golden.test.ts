/**
 * The customer-visible half of the net under the asserted-ratification migration.
 *
 * Spec §7.1 requires two recorded levels, because the engine golden cannot see
 * the frontend: the reason copy a customer reads, the four-question cut, the
 * dedupe to one determination per requirement, the applies/does-not-apply
 * counts, and the citation titles all live in `checkResponse.ts` and `pack.ts`.
 * A change confined to those files moves what a customer reads while leaving
 * `AssessmentResult` untouched, so only this golden reports it.
 *
 * Spec §7.2 holds this level to **exact observable equality**: nothing about the
 * customer-visible surface is intended to change across the migration, so
 * nothing may. That is why the artifact is plain `JSON.stringify` of the payload
 * rather than a canonicalised form — key order is part of the bytes the route
 * hands back, and the standard here is byte-identity, not logical equivalence.
 *
 * The date is a literal. `buildCheckResponse` takes the assessment date as an
 * argument precisely so this can be pinned; the route computes it as a **UTC**
 * day while the machine running the tests may be on a different local one, so a
 * golden keyed to an ambient date would go red once a day for no reason.
 *
 * **This artifact is updated only by an explicit, reviewed change.** There is no
 * regeneration script anywhere in this repository, and this test never writes.
 * A red golden means the customer-visible payload moved: read the diff and
 * decide whether the move was intended. Regenerating it to green is not a fix —
 * it deletes the only evidence that the surface changed at all.
 */

import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { buildCheckResponse, type CheckResponse } from '@/lib/checkResponse';
import { csrdPack } from '@/lib/pack';
import type { CheckerAnswers } from '@/lib/checker';

const ARTIFACT = fileURLToPath(new URL('./golden/migration-public-golden.json', import.meta.url));

/**
 * A German entity over both thresholds, answering every question the check
 * asks — the widest slice the public surface can reach. Above both thresholds
 * so determinations, obligations and next questions are all populated; the
 * public check never collects `readiness.*` facts, so its gap list is
 * legitimately empty and the engine golden is what covers that path.
 */
const FIXED_ANSWERS: CheckerAnswers = {
  country: 'DE',
  legalForm: 'private_limited_company',
  financialYear: '2027',
  groupPosition: 'standalone',
  turnover: 'gt600',
  employees: 'gt1500',
  reportedFy2024: 'no',
  governingChoice: 'same',
};

/** The same day `ctx` pins for the engine golden, and deliberately in the past. */
const FIXED_DATE = '2026-07-26';

function readArtifact(): string {
  try {
    return readFileSync(ARTIFACT, 'utf8');
  } catch {
    throw new Error(
      `Recorded golden missing: ${ARTIFACT}. It is created and updated only by an ` +
        'explicit, reviewed change — never regenerated by a test or a migration.',
    );
  }
}

const payload = () => buildCheckResponse(csrdPack(), FIXED_ANSWERS, FIXED_DATE);

const serialise = (value: CheckResponse) => `${JSON.stringify(value, null, 2)}\n`;

describe('public migration golden', () => {
  it('matches the recorded artifact exactly', () => {
    const recorded = readArtifact();
    const actual = serialise(payload());
    // Structural comparison first: on failure vitest names the field that moved.
    expect(JSON.parse(actual)).toEqual(JSON.parse(recorded));
    // Then the bytes, which also hold key order and array order.
    expect(actual).toBe(recorded);
  });

  it('captures a substantial payload, so agreement means something', () => {
    const recorded = JSON.parse(readArtifact()) as CheckResponse;
    expect(recorded.determinations.length).toBeGreaterThanOrEqual(1);
    expect(recorded.obligations.length).toBeGreaterThanOrEqual(1);
    expect(recorded.nextQuestions.length).toBeGreaterThanOrEqual(1);
    expect(recorded.containsDraftContent).toBe(true);
    expect(recorded.headline.length).toBeGreaterThan(0);
    // The frontend-only fields the engine golden cannot see are actually present.
    expect(recorded.determinations.some((d) => d.reasonCopy !== undefined)).toBe(true);
    expect(recorded.determinations.some((d) => d.sources.length > 0)).toBe(true);
    expect(recorded.counts.applies).toBeGreaterThanOrEqual(1);
  });

  it('is a capture of fixed inputs, not of the day it ran', () => {
    const recorded = JSON.parse(readArtifact()) as CheckResponse;
    expect(recorded.assessedAt).toBe(FIXED_DATE);
    expect(recorded.assessedAt).not.toBe(new Date().toISOString().slice(0, 10));
    expect(recorded.financialYear).toEqual({ start: '2027-01-01', end: '2027-12-31' });
  });
});
